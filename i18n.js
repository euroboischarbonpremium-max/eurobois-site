const flagCodes = { de: "de", en: "gb", lt: "lt" };
const langLabels = { de: "DE", en: "EN", lt: "LT" };

function t(key) {
    const lang = localStorage.getItem("eurobois-lang") || "lt";
    const dict = translations[lang] || translations.lt;
    return dict[key] || key;
}

function applyLanguage(lang) {
    if (!translations[lang]) lang = "lt";
    const dict = translations[lang];
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        const key = el.getAttribute("data-i18n");
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key] !== undefined) {
            el.setAttribute("placeholder", dict[key]);
        }
    });
    document.querySelectorAll(".lang-flag-current").forEach(function (img) {
        img.src = "https://flagcdn.com/16x12/" + flagCodes[lang] + ".png";
    });
    document.querySelectorAll(".lang-label-current").forEach(function (span) {
        span.textContent = langLabels[lang];
    });
    document.documentElement.setAttribute("lang", lang);
    localStorage.setItem("eurobois-lang", lang);
    if (typeof renderCart === "function") {
        try { renderCart(); } catch (e) {}
    }
}

function setLanguage(lang) {
    applyLanguage(lang);
    document.querySelectorAll(".lang-menu").forEach(function (m) {
        m.classList.add("hidden");
    });
}

function toggleLangMenu() {
    document.querySelectorAll(".lang-menu").forEach(function (m) {
        m.classList.toggle("hidden");
    });
}

document.addEventListener("click", function (e) {
    if (!e.target.closest(".lang-switcher")) {
        document.querySelectorAll(".lang-menu").forEach(function (m) {
            m.classList.add("hidden");
        });
    }
});

document.addEventListener("DOMContentLoaded", function () {
    const saved = localStorage.getItem("eurobois-lang") || "lt";
    applyLanguage(saved);
});


